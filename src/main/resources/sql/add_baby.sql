-- 육아 기록(아기 관리) 테이블: 아기, 보호자, 초대 코드, 기록
CREATE TABLE TBABY_BABY (
    BABY_ID             NUMBER              PRIMARY KEY,
    NAME                VARCHAR2(50 CHAR)   NOT NULL,
    BIRTH_DATE          DATE                NOT NULL,
    GENDER              VARCHAR2(1),
    FEED_REMIND_HOURS   NUMBER(3,1)         DEFAULT 0 NOT NULL,
    LAST_REMIND_LOG_ID  NUMBER,
    CREATED_BY          VARCHAR2(50),
    CREATED_AT          DATE                DEFAULT SYSDATE,
    IS_HIDDEN           NUMBER(1)           DEFAULT 0 NOT NULL
);
CREATE SEQUENCE TBABY_BABY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE TBABY_MEMBER (
    BABY_ID           NUMBER              NOT NULL,
    KAKAO_ID          VARCHAR2(50)        NOT NULL,
    RELATION          VARCHAR2(20 CHAR),
    NOTIFY_ACTIVITY   VARCHAR2(1)         DEFAULT 'Y' NOT NULL,
    NOTIFY_REMIND     VARCHAR2(1)         DEFAULT 'Y' NOT NULL,
    IS_OWNER          NUMBER(1)           DEFAULT 0 NOT NULL,
    JOINED_AT         DATE                DEFAULT SYSDATE,
    CONSTRAINT PK_TBABY_MEMBER PRIMARY KEY (BABY_ID, KAKAO_ID)
);
CREATE INDEX IDX_TBABY_MEMBER_USER ON TBABY_MEMBER (KAKAO_ID);
CREATE TABLE TBABY_INVITE (
    CODE         VARCHAR2(12)   PRIMARY KEY,
    BABY_ID      NUMBER         NOT NULL,
    CREATED_BY   VARCHAR2(50),
    EXPIRES_AT   DATE           NOT NULL,
    USED_BY      VARCHAR2(50),
    USED_AT      DATE
);
CREATE TABLE TBABY_LOG (
    LOG_ID       NUMBER              PRIMARY KEY,
    BABY_ID      NUMBER              NOT NULL,
    LOG_TYPE     VARCHAR2(10)        NOT NULL,
    START_AT     DATE                NOT NULL,
    END_AT       DATE,
    ML           NUMBER(6,1),
    DETAIL       VARCHAR2(20),
    WEIGHT_KG    NUMBER(5,2),
    HEIGHT_CM    NUMBER(5,1),
    HEAD_CM      NUMBER(5,1),
    TEMP_C       NUMBER(3,1),
    MEMO         VARCHAR2(300 CHAR),
    CREATED_BY   VARCHAR2(50),
    CREATED_AT   DATE                DEFAULT SYSDATE,
    IS_HIDDEN    NUMBER(1)           DEFAULT 0 NOT NULL
);
CREATE SEQUENCE TBABY_LOG_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE INDEX IDX_TBABY_LOG_BABY_START ON TBABY_LOG (BABY_ID, START_AT);
